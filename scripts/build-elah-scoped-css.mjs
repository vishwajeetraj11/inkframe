import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import postcss from "postcss";

const require = createRequire(import.meta.url);
const outputPath = path.resolve(
  "src/components/editor/elah/elah-vendor-scoped.css",
);
const sourcePaths = [
  require.resolve("@elah/editor/styles.css"),
  require.resolve("@elah/timeline/styles.css"),
];

const scopeCss = async (sourcePath) => {
  const css = await readFile(sourcePath, "utf8");
  const root = postcss.parse(css, { from: sourcePath });

  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && rule.parent.name.endsWith("keyframes")) {
      return;
    }

    rule.selectors = rule.selectors.map((selector) => `.inkframe-elah ${selector}`);
  });

  return root.toString();
};

const scopedSources = await Promise.all(sourcePaths.map(scopeCss));
const banner =
  "/* Generated by scripts/build-elah-scoped-css.mjs. Do not edit directly. */\n";

await writeFile(outputPath, `${banner}${scopedSources.join("\n")}\n`, "utf8");
